export const interpolateEditorLabel = (
  template: string,
  variables: Record<string, string | number> = {}
): string =>
  template.replace(/\{\s*\$\s*([a-zA-Z0-9_]+)\s*\}/gu, (match, name: string) =>
    Object.hasOwn(variables, name) ? String(variables[name]) : match
  )

export const buildEditorLabels = (catalogue: EditorCatalogue = {}): EditorLabels => {
  const resolved = {} as EditorLabels
  for (const id of Object.keys(editorLabelKeys) as EditorLabelId[]) {
    const key = editorLabelKeys[id]
    const translated = catalogue[key]
    resolved[id] =
      typeof translated === "string" && translated.trim() !== "" && translated !== key
        ? translated
        : editorEnglishLabels[id]
  }
  return resolved
}
